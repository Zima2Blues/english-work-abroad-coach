#!/usr/bin/env python3
"""Install a user-level systemd timer for daily English reminders."""

import argparse
import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path


UNIT_NAME = "english-work-abroad-coach"
UNINSTALL_MARKER_NAME = "uninstall.systemd.sh"
_APPLICATION_STATE_DIR = "english-work-abroad-coach"


def state_base_dir():
    """Return the user state directory for the uninstall marker.

    Uses a live environment (so tests can point it at a temp directory) and the
    literal path without resolve(), matching the platform user-state layout.
    """
    base = os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local" / "state")
    return Path(base) / _APPLICATION_STATE_DIR


def install_marker(state_dir):
    """Write an executable shell script that removes the installed timer.

    The marker lives outside the skill folder so it still works after the folder
    has been deleted. It stops the user timer, removes both unit files, and
    reloads systemd; stop failures are tolerated, matching uninstall().
    """
    state_dir = Path(state_dir)
    state_dir.mkdir(parents=True, exist_ok=True)
    marker = state_dir / UNINSTALL_MARKER_NAME
    marker.write_text(
        "#!/bin/sh\n"
        "# Generated by the English Work Abroad Coach skill.\n"
        "# Safe to run after the skill folder is deleted: stops and removes\n"
        "# the installed reminder timer. Learning data is left untouched.\n"
        "set -e\n"
        "systemctl --user disable --now %s.timer || true\n"
        "rm -f \"$HOME/.config/systemd/user/%s.service\" \\\n"
        "      \"$HOME/.config/systemd/user/%s.timer\"\n"
        "systemctl --user daemon-reload || true\n"
        % (UNIT_NAME, UNIT_NAME, UNIT_NAME),
        encoding="utf-8",
    )
    marker.chmod(0o755)
    return marker


def skill_root():
    return Path(__file__).resolve().parents[1]


def load_coach_storage():
    """Load the sibling storage module when this file runs as a script."""
    script = Path(__file__).resolve().parent / "coach_storage.py"
    spec = importlib.util.spec_from_file_location("coach_storage", script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


coach_storage = load_coach_storage()


def validate_time(value):
    if not re.match(r"^[0-2][0-9]:[0-5][0-9]$", value):
        raise ValueError("Time must be HH:MM, for example 21:00")
    hour, minute = [int(part) for part in value.split(":")]
    if hour > 23 or minute > 59:
        raise ValueError("Time must be a valid 24-hour HH:MM value")
    return value


def quote_systemd_value(value):
    """Quote one systemd unit value without routing it through a shell."""
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"%s"' % escaped


def escape_systemd_path(value):
    """Encode a path directive, whose values do not support double quotes."""
    replacements = {
        " ": "\\x20",
        "\\": "\\x5c",
        '"': "\\x22",
        "\t": "\\x09",
        "\n": "\\x0a",
        "\r": "\\x0d",
        "%": "%%",
    }
    return "".join(replacements.get(character, character) for character in str(value))


def resolve_install_state_dir(state_dir=None):
    """Resolve the state location once so the timer has an explicit path."""
    return coach_storage.resolve_state_dir(explicit=state_dir).expanduser().resolve()


def build_systemd_units(root, reminder_time, state_dir=None):
    root = Path(root).resolve()
    state_dir = resolve_install_state_dir(state_dir)
    reminder_time = validate_time(reminder_time)
    python = root / ".venv" / "bin" / "python"
    runner = root / "scripts" / "reminder_runner.py"
    service = """[Unit]
Description=English Work Abroad Coach reminder

[Service]
Type=oneshot
WorkingDirectory=%s
ExecStart=%s %s --root %s --state-dir %s
""" % (
        escape_systemd_path(root),
        quote_systemd_value(python),
        quote_systemd_value(runner),
        quote_systemd_value(root),
        quote_systemd_value(state_dir),
    )
    timer = """[Unit]
Description=Daily English Work Abroad Coach reminder

[Timer]
OnCalendar=*-*-* %s:00
Persistent=true

[Install]
WantedBy=timers.target
""" % reminder_time
    return {"service": service, "timer": timer}


def unit_paths(systemd_user_dir):
    base = Path(systemd_user_dir).expanduser()
    return {
        "service": base / ("%s.service" % UNIT_NAME),
        "timer": base / ("%s.timer" % UNIT_NAME),
    }


def write_units(root, reminder_time, systemd_user_dir, state_dir=None):
    paths = unit_paths(systemd_user_dir)
    units = build_systemd_units(root, reminder_time, state_dir)
    paths["service"].parent.mkdir(parents=True, exist_ok=True)
    paths["service"].write_text(units["service"], encoding="utf-8")
    paths["timer"].write_text(units["timer"], encoding="utf-8")
    return paths


def run(command, dry_run=False):
    print("+ " + " ".join(command))
    if not dry_run:
        subprocess.run(command, check=True)


def install(
    root,
    reminder_time="21:00",
    dry_run=False,
    systemd_user_dir=None,
    enable=True,
    state_dir=None,
):
    root = Path(root).resolve()
    if not (root / ".venv" / "bin" / "python").exists():
        raise FileNotFoundError("Missing .venv. Run scripts/bootstrap.py first.")
    systemd_dir = Path(systemd_user_dir).expanduser() if systemd_user_dir else Path.home() / ".config" / "systemd" / "user"
    paths = write_units(root, reminder_time, systemd_dir, state_dir)
    marker = None
    if enable and not dry_run and sys.platform.startswith("linux"):
        marker = install_marker(resolve_install_state_dir(state_dir))
    if enable:
        run(["systemctl", "--user", "daemon-reload"], dry_run=dry_run)
        run(["systemctl", "--user", "enable", "--now", "%s.timer" % UNIT_NAME], dry_run=dry_run)
    return {"units": paths, "marker": marker}


def uninstall(root=None, dry_run=False, systemd_user_dir=None):
    """Stop the reminder timer, remove its unit files, and reload systemd.

    This tears down only the installed systemd units. It never touches the user
    state database, so learning data survives a skill uninstall.
    """
    systemd_dir = Path(systemd_user_dir).expanduser() if systemd_user_dir else Path.home() / ".config" / "systemd" / "user"
    paths = unit_paths(systemd_dir)
    removed = [path for path in paths.values() if path.exists()]

    if dry_run:
        return removed

    subprocess.run(
        ["systemctl", "--user", "disable", "--now", "%s.timer" % UNIT_NAME],
        check=False,
    )
    for path in removed:
        path.unlink()
    if removed:
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=False)
    return removed


def build_parser():
    parser = argparse.ArgumentParser(description="Install or uninstall a daily user-level systemd reminder timer.")
    parser.add_argument("--root", default=str(skill_root()))
    parser.add_argument("--state-dir", help="Writable user state folder used by the reminder.")
    parser.add_argument("--time", default="21:00", help="Daily reminder time in HH:MM. Default: 21:00.")
    parser.add_argument("--systemd-user-dir", help="Override unit output directory for testing.")
    parser.add_argument("--dry-run", action="store_true", help="Write unit files but do not enable the timer.")
    parser.add_argument("--no-enable", action="store_true", help="Write unit files but do not run systemctl.")
    parser.add_argument("--uninstall", action="store_true", help="Remove the reminder timer and its unit files.")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.uninstall:
        removed = uninstall(
            args.root,
            dry_run=args.dry_run,
            systemd_user_dir=args.systemd_user_dir,
        )
        if removed:
            for path in removed:
                print("Removed %s" % path)
        else:
            print("No reminder timer unit found.")
        if args.dry_run:
            print("Timer removal not performed because --dry-run was passed.")
        return 0
    paths = install(
        args.root,
        args.time,
        dry_run=args.dry_run,
        systemd_user_dir=args.systemd_user_dir,
        enable=not args.no_enable,
        state_dir=args.state_dir,
    )
    print("Installed %s" % paths["units"]["service"])
    print("Installed %s" % paths["units"]["timer"])
    if paths["marker"]:
        print("Installed uninstall marker: %s" % paths["marker"])
        print("Rerun it later to stop the timer after deleting the skill folder.")
    if args.no_enable:
        print("Timer not enabled because --no-enable was passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
